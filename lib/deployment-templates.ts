import type { AgentSpec } from "@/lib/agent-spec";
import {
  resolveAgentDeployment,
  resolveAgentUi,
  type AgentDeployment,
  type DeploymentFile,
  type DeploymentPlatform,
} from "@/lib/agent-ui";
import {
  buildDeployFileBundle,
  getDeployCustomCss,
} from "@/lib/deploy-html";

function buildHtmlFiles(spec: AgentSpec): DeploymentFile[] {
  return buildDeployFileBundle(spec, getDeployCustomCss(spec)).map((file) => ({
    path: file.path,
    language: file.language,
    content: file.content,
  }));
}

function buildTypeScriptFile(spec: AgentSpec): DeploymentFile {
  const ui = resolveAgentUi(spec.ui);
  const content = `/**
 * ${spec.name} — TypeScript agent client
 * Generated by Swarm Agent Builder
 */

export interface AgentConfig {
  name: string;
  instructions: string;
  persona: { role: string; tone: string };
  apiEndpoint: string;
}

export const agentConfig: AgentConfig = {
  name: ${JSON.stringify(spec.name)},
  instructions: ${JSON.stringify(spec.instructions)},
  persona: ${JSON.stringify(spec.persona)},
  apiEndpoint: process.env.AGENT_API_URL ?? "http://localhost:3000/api/chat",
};

export interface AgentTheme {
  primaryColor: string;
  mode: "light" | "dark" | "auto";
}

export const agentTheme: AgentTheme = {
  primaryColor: ${JSON.stringify(ui.theme.primaryColor)},
  mode: ${JSON.stringify(ui.theme.mode)},
};

export interface ChatMessage {
  role: "user" | "assistant";
  content: string;
}

export async function sendMessage(
  messages: ChatMessage[]
): Promise<string> {
  const response = await fetch(agentConfig.apiEndpoint, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      messages,
      agentSpec: {
        name: agentConfig.name,
        instructions: agentConfig.instructions,
        persona: agentConfig.persona,
        tools: ${JSON.stringify(spec.tools)},
      },
    }),
  });

  if (!response.ok) {
    throw new Error(\`Agent request failed: \${response.status}\`);
  }

  const data = await response.json();
  return data.reply ?? data.text ?? "";
}
`;

  return { path: "agent-client.ts", language: "typescript", content };
}

function buildPythonFile(spec: AgentSpec): DeploymentFile {
  const ui = resolveAgentUi(spec.ui);
  const content = `"""
${spec.name} — Python agent client
Generated by Swarm Agent Builder
"""

import json
import os
from typing import Any

AGENT_CONFIG = {
    "name": ${JSON.stringify(spec.name)},
    "instructions": ${JSON.stringify(spec.instructions)},
    "persona": ${JSON.stringify(spec.persona)},
    "tools": ${JSON.stringify(spec.tools)},
}

AGENT_THEME = {
    "primary_color": ${JSON.stringify(ui.theme.primaryColor)},
    "mode": ${JSON.stringify(ui.theme.mode)},
}

API_ENDPOINT = os.environ.get("AGENT_API_URL", "http://localhost:3000/api/chat")


def send_message(messages: list[dict[str, str]]) -> str:
    """Send a conversation to the agent runtime and return the reply."""
    import urllib.request

    payload = json.dumps({
        "messages": messages,
        "agentSpec": AGENT_CONFIG,
    }).encode("utf-8")

    req = urllib.request.Request(
        API_ENDPOINT,
        data=payload,
        headers={"Content-Type": "application/json"},
        method="POST",
    )

    with urllib.request.urlopen(req) as response:
        data = json.loads(response.read().decode("utf-8"))
        return data.get("reply") or data.get("text") or ""


if __name__ == "__main__":
    reply = send_message([{"role": "user", "content": "Hello!"}])
    print(reply)
`;

  return { path: "agent_client.py", language: "python", content };
}

